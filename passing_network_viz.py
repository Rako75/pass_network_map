def plot_professional_network(average_locs, pass_between, G, team_stats=None, match_info=None, analyzed_team_name="ÉQUIPE"):

    # --- Polices ---
    try:
        font_bold = FontManager(ModernTheme.FONT_BOLD_URL).prop
        font_reg = FontManager(ModernTheme.FONT_REG_URL).prop
    except:
        font_bold = None
        font_reg = None

    # --- Terrain ---
    pitch = Pitch(
        pitch_type='opta',
        pitch_color=ModernTheme.PITCH_COLOR,
        line_color=ModernTheme.PITCH_LINES,
        linewidth=1.5,
        goal_type='box',
        pad_top=4, pad_bottom=0.5, pad_left=0.5, pad_right=0.5
    )

    fig, ax = pitch.draw(figsize=(16, 12), constrained_layout=True)
    fig.set_facecolor(ModernTheme.BACKGROUND)

    # --- Colormap ---
    cmap_passes = LinearSegmentedColormap.from_list("PassAcc", [
        ModernTheme.PASS_LOW, ModernTheme.PASS_MID, ModernTheme.PASS_HIGH
    ])
    norm = Normalize(vmin=70, vmax=100)

    # --- Seuils ---
    max_passes_val = 0
    strong_thresh_val = 0

    # --- Tracé des Passes ---
    if not pass_between.empty:
        min_pass_threshold = 1
        pass_between = pass_between[pass_between['pass_count'] >= min_pass_threshold].copy()

        max_passes_val = pass_between['pass_count'].max()
        strong_thresh_val = int(max_passes_val * 0.8)

        pass_between = pass_between.sort_values('pass_count')

        for _, row in pass_between.iterrows():
            pass_strength = row['pass_count'] / max_passes_val
            width = (pass_strength ** 1.2) * 8 + 0.3
            alpha = max(0.15, (pass_strength ** 1.5) * 0.7 + 0.15)

            if pass_strength > 0.8:
                color_line = ModernTheme.LINK_STRONG
                z_ord = 2
            else:
                color_line = ModernTheme.LINK_WEAK
                z_ord = 1

            pitch.lines(
                row.x, row.y, row.x_end, row.y_end,
                lw=width, color=color_line, alpha=alpha,
                ax=ax, zorder=z_ord, capstyle='round'
            )

    # --- Tracé des Joueurs ---
    max_eigen = average_locs['eigenvector_centrality'].max()
    sizes = (average_locs['eigenvector_centrality'] / max_eigen * 2800) + 600

    starters = average_locs[average_locs['player_position'] != 'Sub']
    subs = average_locs[average_locs['player_position'] == 'Sub']

    def draw_nodes(nodes_df, marker_shape, is_sub=False):
        if nodes_df.empty: return
        node_sizes = sizes.loc[nodes_df.index]
        if is_sub: node_sizes = node_sizes * 0.7
        node_colors = nodes_df['pass_accuracy']

        # Glow
        pitch.scatter(nodes_df.x, nodes_df.y, s=node_sizes * 1.2, marker=marker_shape,
            c=ModernTheme.BACKGROUND, edgecolors=ModernTheme.TEXT_MUTED, linewidth=1, alpha=0.4, ax=ax, zorder=3)
        # Core
        pitch.scatter(nodes_df.x, nodes_df.y, s=node_sizes, marker=marker_shape,
            c=node_colors, cmap=cmap_passes, norm=norm, edgecolors='white', linewidth=2, alpha=1, ax=ax, zorder=4)

    draw_nodes(starters, marker_shape='o', is_sub=False)
    draw_nodes(subs, marker_shape='D', is_sub=True)

    # --- Annotations Joueurs ---
    txt_effects = [path_effects.Stroke(linewidth=4, foreground=ModernTheme.BACKGROUND), path_effects.Normal()]

    for player_id, row in average_locs.iterrows():
        is_sub = row.player_position == 'Sub'
        jersey = str(int(row.jersey_number)) if 'jersey_number' in row and not pd.isna(row.jersey_number) else ""
        text_color_inner = 'black' if row['pass_accuracy'] > 85 else 'white'

        pitch.annotate(jersey, xy=(row.x, row.y), ax=ax, zorder=6,
            va="center", ha="center", size=11 if is_sub else 13,
            color=text_color_inner, weight='bold', fontproperties=font_bold)

        name = str(row.player_name).split(" ")[-1].upper()
        if len(name) > 10: name = name[:9] + "."
        t = pitch.annotate(name, xy=(row.x, row.y - (4.5 if not is_sub else 4.0)), ax=ax, zorder=7,
            va="center", ha="center", size=9 if is_sub else 11, color='white', fontproperties=font_bold)
        t.set_path_effects(txt_effects)

    # --- EN-TÊTE DU MATCH ---
    if match_info:
        home_name = match_info.get('home_name', 'HOME').upper()
        away_name = match_info.get('away_name', 'AWAY').upper()
        score_text = f"{match_info.get('home_score', 0)} - {match_info.get('away_score', 0)}"

        text_y = 0.95
        logo_y = 0.915
        logo_dim = 0.07
        pivot_x = 0.25
        gap_from_score = 0.06

        def add_logo_to_fig(image_path, position_rect):
            if os.path.exists(image_path):
                try:
                    img = mpimg.imread(image_path)
                    logo_ax = fig.add_axes(position_rect, zorder=10)
                    logo_ax.imshow(img)
                    logo_ax.axis('off')
                except Exception as e:
                    print(f"Erreur logo: {e}")

        # Score
        fig.text(pivot_x, text_y, score_text, size=28, color='white', ha='center', va='center', fontproperties=font_bold)

        # Noms
        fig.text(pivot_x - gap_from_score, text_y, home_name, size=24, color='white', ha='right', va='center', fontproperties=font_bold)
        fig.text(pivot_x + gap_from_score, text_y, away_name, size=24, color='white', ha='left', va='center', fontproperties=font_bold)

        # Logos - bien espacés des noms
        add_logo_to_fig('Fulham.png', [0.03, logo_y, logo_dim, logo_dim])
        add_logo_to_fig('Man City.png', [0.42, logo_y, logo_dim, logo_dim])

        # Sous-titre
        fig.text(0.04, 0.88, f"ANALYSE : {analyzed_team_name.upper()}", size=14, color=ModernTheme.PRIMARY, fontproperties=font_reg)

    else:
        fig.text(0.02, 0.96, analyzed_team_name.upper(), size=30, color='white', ha='left', fontproperties=font_bold)

    # Colorbar
    cax = fig.add_axes([0.78, 0.03, 0.18, 0.02])
    cbar = plt.colorbar(ScalarMappable(norm=norm, cmap=cmap_passes), cax=cax, orientation='horizontal')
    cbar.ax.tick_params(labelsize=9, colors='white')
    cbar.outline.set_edgecolor(ModernTheme.TEXT_MUTED)
    fig.text(0.87, 0.06, "PRÉCISION DES PASSES (%)", ha='center', color='white', size=10, fontproperties=font_bold)

    # --- KPI STATS ---
    stats_label_y = 0.94
    stats_value_y = 0.915

    def add_stat_line(label, value, x_pos, color=ModernTheme.PRIMARY, is_name=False):
        fig.text(x_pos, stats_label_y, label, color=ModernTheme.TEXT_MUTED, size=9, fontproperties=font_reg, ha='center')
        size_val = 14 if is_name else 18
        fig.text(x_pos, stats_value_y, value, color=color, size=size_val, fontproperties=font_bold, ha='center')

    if team_stats:
        possession = f"{team_stats.get('possession_percentage', 0)}%"
        total_p = str(team_stats.get('total_passes', 0))
        success_p = str(team_stats.get('successful_passes', 0))
        acc_p = f"{team_stats.get('pass_accuracy', 0)}%"

        add_stat_line("POSSESSION", possession, 0.58, ModernTheme.PRIMARY)
        add_stat_line("TOTAL PASSES", total_p, 0.68, 'white')
        add_stat_line("PASSES RÉUSSIES", success_p, 0.78, ModernTheme.PASS_HIGH)
        add_stat_line("PRÉCISION", acc_p, 0.88, cmap_passes(norm(team_stats.get('pass_accuracy', 0))))

    # MENEUR DE JEU
    top_player = average_locs.sort_values('eigenvector_centrality', ascending=False).iloc[0]
    player_name = str(top_player.player_name).split(" ")[-1]
    add_stat_line("MENEUR DE JEU", player_name, 0.96, ModernTheme.ACCENT, is_name=True)

    # --- Légende ---
    legend_ax = fig.add_axes([0.02, 0.02, 0.60, 0.08])
    legend_ax.axis('off')
    legend_ax.set_xlim(0, 1)
    legend_ax.set_ylim(0, 1)

    legend_ax.scatter(0.04, 0.7, s=120, marker='o', c=ModernTheme.BACKGROUND, edgecolors='white', lw=2)
    legend_ax.text(0.07, 0.7, "Titulaire", color='white', va='center', size=10, fontproperties=font_reg)
    legend_ax.scatter(0.18, 0.7, s=100, marker='D', c=ModernTheme.BACKGROUND, edgecolors='white', lw=2)
    legend_ax.text(0.21, 0.7, "Remplaçant", color='white', va='center', size=10, fontproperties=font_reg)

    legend_ax.plot([0.33, 0.38], [0.7, 0.7], color=ModernTheme.LINK_WEAK, lw=2, alpha=0.6)
    legend_ax.text(0.39, 0.7, "Standard", color=ModernTheme.TEXT_SECONDARY, va='center', size=9, fontproperties=font_reg)

    legend_ax.plot([0.55, 0.60], [0.7, 0.7], color=ModernTheme.LINK_STRONG, lw=4)
    label_forte = f"Liaison Forte (>{strong_thresh_val} passes)"
    legend_ax.text(0.61, 0.7, label_forte, color=ModernTheme.PRIMARY, va='center', size=9, weight='bold', fontproperties=font_bold)

    legend_ax.text(0.04, 0.3, "TAILLE :", color=ModernTheme.ACCENT, size=9, fontproperties=font_bold)
    legend_ax.text(0.10, 0.3, "Influence", color='white', size=9, fontproperties=font_reg)
    legend_ax.text(0.40, 0.3, "COULEUR :", color=ModernTheme.PASS_HIGH, size=9, fontproperties=font_bold)
    legend_ax.text(0.48, 0.3, "Précision (%)", color='white', size=9, fontproperties=font_reg)

    return fig

