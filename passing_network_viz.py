def calculate_advanced_metrics(team_passes, team_events):
    agg_dict = {'x': 'mean', 'y': 'mean', 'id': 'count'}
    for col in ['player_name', 'jersey_number', 'player_position']:
        if col in team_passes.columns: agg_dict[col] = 'first'

    average_locs = team_passes.groupby('player_id').agg(agg_dict)
    average_locs.rename(columns={'id': 'successful_pass_count'}, inplace=True)

    type_col = 'type_display_name' if 'type_display_name' in team_events.columns else 'type'
    all_passes = team_events[team_events[type_col] == 'Pass'].groupby('player_id').size()
    average_locs['total_attempts'] = all_passes
    average_locs['pass_accuracy'] = (average_locs['successful_pass_count'] / average_locs['total_attempts'] * 100).fillna(0)

    pass_between = team_passes.groupby(['player_id', 'recipient_id']).agg({'id': 'count'}).reset_index()
    pass_between.rename(columns={'id': 'pass_count'}, inplace=True)

    G = nx.DiGraph()
    for _, row in pass_between.iterrows():
        G.add_edge(row['player_id'], row['recipient_id'], weight=row['pass_count'])

    try:
        average_locs['eigenvector_centrality'] = pd.Series(nx.eigenvector_centrality(G, weight='weight', max_iter=1000))
    except:
        average_locs['eigenvector_centrality'] = 0.1

    pass_between = pass_between.merge(average_locs[['x', 'y']], left_on='player_id', right_index=True)
    pass_between = pass_between.merge(average_locs[['x', 'y']], left_on='recipient_id', right_index=True, suffixes=('', '_end'))

    return average_locs, pass_between, G

