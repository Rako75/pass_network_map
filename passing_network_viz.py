def parse_qualifiers(row):
    try:
        if pd.isna(row): return {}
        quals = json.loads(row) if isinstance(row, str) else row
        qual_dict = {}
        for q in quals:
            if 'type' in q and 'displayName' in q['type']:
                key = q['type']['displayName']
                value = q.get('value', True)
                qual_dict[key] = value
        return qual_dict
    except Exception:
        return {}

def load_and_process_data(events_path, players_path, target_team_id=None):
    events = pd.read_csv(events_path)
    players = pd.read_csv(players_path)

    if 'qualifiers' in events.columns:
        qual_data = events['qualifiers'].apply(parse_qualifiers).apply(pd.Series)
        events = pd.concat([events, qual_data], axis=1)

    players_renamed = players.rename(columns={
        'name': 'player_name',
        'shirt_no': 'jersey_number',
        'position': 'player_position',
        'id': 'player_id_key'
    })

    df = events.merge(players_renamed, left_on='player_id', right_on='player_id', how='left', suffixes=('', '_player'))

    team_col = next((col for col in df.columns if 'team' in col.lower() and 'id' in col.lower()), None)
    if not team_col: raise ValueError("Pas de colonne team_id trouvée.")

    sort_cols = [c for c in ['period_display_name', 'minute', 'second', 'id'] if c in df.columns]
    df = df.sort_values(by=sort_cols).reset_index(drop=True)

    df['next_player_id'] = df['player_id'].shift(-1)
    df['next_team_id'] = df[team_col].shift(-1)

    type_col = 'type_display_name' if 'type_display_name' in df.columns else 'type'
    outcome_col = 'outcome_type_display_name' if 'outcome_type_display_name' in df.columns else 'outcome'

    passes = df[
        (df[type_col] == 'Pass') &
        (df[outcome_col] == 'Successful') &
        (df[team_col] == df['next_team_id']) &
        (df['next_player_id'].notnull())
    ].copy()

    passes['recipient_id'] = passes['next_player_id']

    if target_team_id is None:
        target_team_id = passes[team_col].mode()[0]

    team_events = df[df[team_col] == target_team_id].copy()

    return passes[passes[team_col] == target_team_id], team_events, team_col

